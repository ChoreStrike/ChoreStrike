#!/usr/bin/env node

/**
 * Agent adapter generator.
 *
 * The canonical, tool-agnostic AI standards live in `docs/standards/ai/`.
 * Coding assistants only discover skills, commands and subagents in their own
 * folders, so this script writes thin generated adapters:
 *
 *   skills/<name>/SKILL.md  → .claude/skills/<name>/SKILL.md (pointer + frontmatter)
 *   commands/<name>.md      → .claude/commands/<name>.md and .kilo/command/<name>.md (copy)
 *   agents/<name>.md        → .claude/agents/<name>.md (copy + Claude tool/model mapping)
 *
 * Kilo reads the canonical skills directly via `skills.paths` in `kilo.jsonc`.
 *
 * Usage:
 *   node scripts/sync-agent-adapters.js          write adapters, remove stale generated ones
 *   node scripts/sync-agent-adapters.js --check  read-only drift gate (exit 1 on drift)
 */

const fs = require('node:fs')
const path = require('node:path')

const SCRIPT_NAME = 'sync-agent-adapters'
const ROOT = path.resolve(__dirname, '..')
const AI_DIR = 'docs/standards/ai'
const MARKER = '<!-- GENERATED by scripts/sync-agent-adapters.js — edit the canonical source, then run `npm run agents:sync`. -->'
const READ_ONLY_TOOLS = 'Read, Grep, Glob'
const READ_ONLY_MODEL = 'sonnet'

const toPosix = p => p.split(path.sep).join('/')
const normalizeEol = text => text.replace(/\r\n/g, '\n')

/** Splits `---` frontmatter into a key/value map and the remaining body. */
function parseFrontmatter(text, file) {
	const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(normalizeEol(text))
	if (!match) throw new Error(`${file}: missing --- frontmatter`)
	const fields = {}
	for (const line of match[1].split('\n')) {
		const kv = /^([\w-]+):\s*(.*)$/.exec(line)
		if (kv) fields[kv[1]] = kv[2].trim()
	}
	return { fields, body: match[2] }
}

function listEntries(root, relDir, filter) {
	const dir = path.join(root, relDir)
	if (!fs.existsSync(dir)) return []
	return fs.readdirSync(dir, { withFileTypes: true }).filter(filter).map(entry => entry.name).sort()
}

function skillAdapter(name, fields, source) {
	if (fields.name !== name) throw new Error(`${source}: frontmatter name "${fields.name}" must equal directory "${name}"`)
	if (!fields.description) throw new Error(`${source}: frontmatter description is required`)
	return [
		'---',
		`name: ${name}`,
		`description: ${fields.description}`,
		'---',
		'',
		MARKER,
		'',
		`Read and follow the canonical skill [\`${source}\`](../../../${source}) now.`,
		'Its relative links resolve from the canonical file\'s directory.',
		'',
	].join('\n')
}

function insertMarker(text) {
	const { fields, body } = parseFrontmatter(text, 'source')
	const head = Object.entries(fields).map(([key, value]) => `${key}: ${value}`)
	return { fields, render: extra => ['---', ...head, ...extra, '---', '', MARKER, '', body.replace(/^\n+/, '')].join('\n') }
}

/** Returns the complete expected adapter set as { relPath: content }. */
function buildAdapters(root = ROOT) {
	const out = {}
	const read = rel => fs.readFileSync(path.join(root, rel), 'utf8')

	for (const name of listEntries(root, `${AI_DIR}/skills`, e => e.isDirectory())) {
		const source = `${AI_DIR}/skills/${name}/SKILL.md`
		out[`.claude/skills/${name}/SKILL.md`] = skillAdapter(name, parseFrontmatter(read(source), source).fields, source)
	}
	for (const file of listEntries(root, `${AI_DIR}/commands`, e => e.isFile() && e.name.endsWith('.md'))) {
		const content = insertMarker(read(`${AI_DIR}/commands/${file}`)).render([])
		out[`.claude/commands/${file}`] = content
		out[`.kilo/command/${file}`] = content
	}
	for (const file of listEntries(root, `${AI_DIR}/agents`, e => e.isFile() && e.name.endsWith('.md'))) {
		const { fields, render } = insertMarker(read(`${AI_DIR}/agents/${file}`))
		const extra = fields['read-only'] === 'true' ? [`tools: ${READ_ONLY_TOOLS}`, `model: ${READ_ONLY_MODEL}`] : []
		out[`.claude/agents/${file}`] = render(extra)
	}
	return out
}

/** Generated files on disk (identified by the marker) that are no longer expected. */
function findStale(root, expected) {
	const stale = []
	const scan = relDir => {
		const dir = path.join(root, relDir)
		if (!fs.existsSync(dir)) return
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			const rel = `${relDir}/${entry.name}`
			if (entry.isDirectory()) scan(rel)
			else if (entry.name.endsWith('.md') && !(rel in expected)
				&& fs.readFileSync(path.join(root, rel), 'utf8').includes(MARKER)) stale.push(rel)
		}
	}
	for (const dir of ['.claude/skills', '.claude/commands', '.claude/agents', '.kilo/command']) scan(dir)
	return stale
}

/** Lists drift findings without writing anything. */
function checkAdapters(root = ROOT) {
	const expected = buildAdapters(root)
	const findings = []
	for (const [rel, content] of Object.entries(expected)) {
		const file = path.join(root, rel)
		if (!fs.existsSync(file)) findings.push(`${rel}: missing`)
		else if (normalizeEol(fs.readFileSync(file, 'utf8')) !== content) findings.push(`${rel}: out of date`)
	}
	for (const rel of findStale(root, expected)) findings.push(`${rel}: stale generated adapter`)
	return findings
}

function syncAdapters(root = ROOT) {
	const expected = buildAdapters(root)
	for (const [rel, content] of Object.entries(expected)) {
		fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true })
		fs.writeFileSync(path.join(root, rel), content)
	}
	const stale = findStale(root, expected)
	for (const rel of stale) {
		fs.rmSync(path.join(root, rel))
		const dir = path.dirname(path.join(root, rel))
		if (fs.readdirSync(dir).length === 0) fs.rmdirSync(dir)
	}
	return { written: Object.keys(expected).length, removed: stale.map(toPosix) }
}

function main() {
	if (process.argv.includes('--check')) {
		const findings = checkAdapters()
		if (findings.length > 0) {
			console.error(`[${SCRIPT_NAME}] ${findings.length} adapter finding(s):`)
			for (const finding of findings) console.error(`  ${finding}`)
			console.error(`[${SCRIPT_NAME}] run \`npm run agents:sync\` and commit the result.`)
			process.exit(1)
		}
		console.log(`[${SCRIPT_NAME}] all agent adapters match ${AI_DIR}/`)
		return
	}
	const { written, removed } = syncAdapters()
	console.log(`[${SCRIPT_NAME}] wrote ${written} adapter(s); removed ${removed.length} stale: ${removed.join(', ') || '—'}`)
}

if (require.main === module) main()

module.exports = { MARKER, buildAdapters, checkAdapters, syncAdapters, parseFrontmatter }
